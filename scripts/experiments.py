#!/usr/bin/env python3
"""Run the measurements behind the report.

    python3 scripts/experiments.py

  1. Memory-latency sweep: the four systems x six benchmarks x 0, 1, 2, 4
     and 8 main-memory wait states (1 KB caches).
  2. Cache-size sweep: split vs unified caches x six benchmarks x 256 B to
     4 KB per split cache (the unified cache is twice that), at 4 wait states.
  3. A cycle trace of the memcpy copy loop on each system (pipeline figure),
     and short VCD files to open in GTKWave.

Writes results/latency_sweep.csv, results/cache_sweep.csv,
results/summary.md, results/trace_memcpy_*.txt and results/waves/*.vcd.
Run verify.py first: this script measures, it does not check correctness.
"""

import csv
import math
from concurrent.futures import ThreadPoolExecutor

import asm
import sim

RESULTS = sim.ROOT / "results"
BENCHMARKS = ["collatz", "crc32", "qsort", "matmul", "listwalk", "memcpy"]
WAITS = [0, 1, 2, 4, 8]
CACHE_SETS = [16, 32, 64, 128, 256]       # 256 B ... 4 KB per split cache
DEFAULT_SETS = 64                         # 1 KB per split cache
SWEEP_WAIT = 4
SYSTEM_NAMES = {
    "vonneumann": "von Neumann",
    "harvard": "Harvard",
    "split_cache": "Split L1 caches",
    "unified_cache": "Unified L1 cache",
}


def run_all(jobs, images):
    """jobs: list of (system, benchmark, wait, sets). Returns a list of result rows."""
    simulators = {}
    for system, _, wait, sets in jobs:
        if (system, wait, sets) not in simulators:
            simulators[(system, wait, sets)] = sim.build_simulator(system, wait, sets)

    def run_job(job):
        system, benchmark, wait, sets = job
        code_hex, data_hex, _ = images[benchmark]
        result = sim.simulate(simulators[(system, wait, sets)], code_hex, data_hex)
        if result["errors"] or result["bus_error"]:
            raise RuntimeError(f"{job}: {result['errors']} (run verify.py)")
        row = {"system": system, "benchmark": benchmark, "mem_wait": wait, "cache_sets": sets}
        row.update(result["stats"])
        row["cpi"] = round(row["cycles"] / row["instret"], 4)
        return row

    with ThreadPoolExecutor() as pool:
        return list(pool.map(run_job, jobs))


def write_csv(path, rows):
    with open(path, "w", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(path.relative_to(sim.ROOT))


def geometric_mean(values):
    return math.exp(sum(math.log(value) for value in values) / len(values))


def summary(latency_rows, cache_rows):
    by_key = {(r["system"], r["benchmark"], r["mem_wait"]): r for r in latency_rows}
    lines = ["# Results summary", "",
             "Generated by `scripts/experiments.py`. CPI = cycles / instructions; lower is better.", ""]

    for wait in (0, SWEEP_WAIT):
        lines += [f"## CPI with {wait} wait states per main-memory word (1 KB caches)", "",
                  "| Benchmark | " + " | ".join(SYSTEM_NAMES.values()) + " |",
                  "|---|" + "---:|" * len(SYSTEM_NAMES)]
        for benchmark in BENCHMARKS:
            cells = [f"{by_key[(system, benchmark, wait)]['cpi']:.2f}" for system in SYSTEM_NAMES]
            lines.append(f"| {benchmark} | " + " | ".join(cells) + " |")
        means = [geometric_mean([by_key[(system, b, wait)]["cpi"] for b in BENCHMARKS]) for system in SYSTEM_NAMES]
        lines.append("| **geometric mean** | " + " | ".join(f"**{mean:.2f}**" for mean in means) + " |")
        lines.append("")

    lines += ["## Geometric-mean CPI against memory wait states", "",
              "| Wait states | " + " | ".join(SYSTEM_NAMES.values()) + " | Split caches vs von Neumann |",
              "|---:|" + "---:|" * (len(SYSTEM_NAMES) + 1)]
    for wait in WAITS:
        means = {system: geometric_mean([by_key[(system, b, wait)]["cpi"] for b in BENCHMARKS]) for system in SYSTEM_NAMES}
        speedup = means["vonneumann"] / means["split_cache"]
        lines.append(f"| {wait} | " + " | ".join(f"{means[s]:.2f}" for s in SYSTEM_NAMES) + f" | {speedup:.2f}x |")
    lines.append("")

    lines += [f"## Where the cycles go ({SWEEP_WAIT} wait states, cycles per instruction by cause)", "",
              "| Benchmark | System | Retire | Fetch stall | Data stall | Load-use | Branch | Other |",
              "|---|---|---:|---:|---:|---:|---:|---:|"]
    for benchmark in ("matmul", "listwalk"):
        for system in SYSTEM_NAMES:
            r = by_key[(system, benchmark, SWEEP_WAIT)]
            n = r["instret"]
            other = r["why_reset"] + r["why_fence"]
            lines.append(f"| {benchmark} | {SYSTEM_NAMES[system]} | 1.00 | {r['why_fetch'] / n:.2f} | {r['why_data'] / n:.2f} | "
                         f"{r['why_load_use'] / n:.2f} | {r['why_branch'] / n:.2f} | {other / n:.3f} |")
    lines.append("")

    lines += ["## Cache behaviour (1 KB per split cache, 2 KB unified)", "",
              "| Benchmark | I-cache hit rate | D-cache hit rate | D-cache write-backs | Unified hit rate | "
              "Memory words per instruction (split) | (unified) | (von Neumann) |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for benchmark in BENCHMARKS:
        split = by_key[("split_cache", benchmark, SWEEP_WAIT)]
        unified = by_key[("unified_cache", benchmark, SWEEP_WAIT)]
        vonneumann = by_key[("vonneumann", benchmark, SWEEP_WAIT)]
        def hit_rate(misses, accesses):
            if accesses == 0:
                return "n/a"                    # collatz never touches cacheable data
            return f"{100 * (1 - misses / accesses):.2f}%"

        def traffic(r):
            return (r["mem_reads"] + r["mem_writes"]) / r["instret"]

        lines.append(f"| {benchmark} | {hit_rate(split['ic_miss'], split['ic_access'])} | "
                     f"{hit_rate(split['dc_miss'], split['dc_access'])} | {split['dc_writeback']} | "
                     f"{hit_rate(unified['dc_miss'], unified['dc_access'])} | "
                     f"{traffic(split):.3f} | {traffic(unified):.3f} | {traffic(vonneumann):.3f} |")
    lines.append("")

    cache_by_key = {(r["system"], r["benchmark"], r["cache_sets"]): r for r in cache_rows}
    lines += [f"## Split vs unified cache of the same total size ({SWEEP_WAIT} wait states, geometric-mean CPI)", "",
              "| Total cache size | Split (I + D) | Unified |", "|---:|---:|---:|"]
    for sets in CACHE_SETS:
        split = geometric_mean([cache_by_key[("split_cache", b, sets)]["cpi"] for b in BENCHMARKS])
        unified = geometric_mean([cache_by_key[("unified_cache", b, sets)]["cpi"] for b in BENCHMARKS])
        lines.append(f"| {2 * sets * 16} B | {split:.2f} | {unified:.2f} |")
    lines.append("")

    path = RESULTS / "summary.md"
    path.write_text("\n".join(lines))
    print(path.relative_to(sim.ROOT))


def write_trace(images):
    """Cycle trace of the memcpy copy loop in steady state, for the pipeline figure."""
    _, _, program = images["memcpy"]
    labels, _, _ = asm.parse((sim.ROOT / "programs" / "memcpy.s").read_text())
    loop_start = labels["copy"]
    for system in SYSTEM_NAMES:
        result = sim.simulate(sim.build_simulator(system, 0, DEFAULT_SETS), *images["memcpy"][:2], trace=True)
        starts = [i for i, line in enumerate(result["trace"]) if f" ex=1:{loop_start:08x} " in line]
        first = starts[2]                                   # third pass: caches warm, loop in steady state
        path = RESULTS / f"trace_memcpy_{system}.txt"
        path.write_text("\n".join(result["trace"][first:first + 40]) + "\n")
        print(path.relative_to(sim.ROOT))


def write_waves(images):
    waves = RESULTS / "waves"
    waves.mkdir(exist_ok=True)
    for system in SYSTEM_NAMES:
        vcd = waves / f"isa_test_{system}.vcd"
        sim.simulate(sim.build_simulator(system, 1, DEFAULT_SETS), *images["isa_test"][:2], vcd=vcd)
        print(vcd.relative_to(sim.ROOT))
    vcd = waves / "smc_test_split_cache.vcd"
    sim.simulate(sim.build_simulator("split_cache", 1, DEFAULT_SETS), *images["smc_test"][:2], vcd=vcd)
    print(vcd.relative_to(sim.ROOT))


def main():
    RESULTS.mkdir(exist_ok=True)
    images = {}
    for name in BENCHMARKS + ["isa_test", "smc_test"]:
        images[name] = sim.assemble(sim.ROOT / "programs" / f"{name}.s", sim.BUILD / name)

    latency_jobs = [(system, benchmark, wait, DEFAULT_SETS)
                    for system in SYSTEM_NAMES for benchmark in BENCHMARKS for wait in WAITS]
    latency_rows = run_all(latency_jobs, images)
    write_csv(RESULTS / "latency_sweep.csv", latency_rows)

    cache_jobs = [(system, benchmark, SWEEP_WAIT, sets)
                  for system in ("split_cache", "unified_cache") for benchmark in BENCHMARKS for sets in CACHE_SETS]
    cache_rows = run_all(cache_jobs, images)
    write_csv(RESULTS / "cache_sweep.csv", cache_rows)

    summary(latency_rows, cache_rows)
    write_trace(images)
    write_waves(images)


if __name__ == "__main__":
    main()
